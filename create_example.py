import argparse
import csv
import json
from pathlib import Path

FIELDS = ["record_id", "entity_name", "entity_id", "event_time", "amount", "country"]


def create_example(destination, rows=100_000):
    destination = Path(destination)
    if destination.exists():
        raise ValueError("Destination already exists.")
    if not 10 <= rows <= 10_000_000:
        raise ValueError("Row count must be between 10 and 10,000,000.")
    destination.mkdir(parents=True)
    with (destination / "records.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(FIELDS)
        for index in range(rows):
            entity = index % 1000
            name = f"  Example   Supply {entity:04d} LLC " if (index // 1000) % 2 else f"EXAMPLE SUPPLY {entity:04d} LIMITED"
            event_time = "2026-09-19" if index % 3 else "09/19/2026"
            amount = "$1,234.50" if index % 5 else ""
            if index % 997 == 0:
                event_time = "invalid-date"
            if index % 991 == 0:
                amount = "not-a-number"
            writer.writerow([f"record-{index}", name, f"entity-{entity}", event_time, amount, " us "])
    (destination / "sources.json").write_text(
        json.dumps({"source": "Deterministic synthetic records generated by create_example.py", "rows": rows, "personal_data": False}, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Created {rows} synthetic records.")


def main():
    parser = argparse.ArgumentParser(description="Generate reproducible synthetic records for validation and scale measurement.")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--rows", type=int, default=100_000)
    arguments = parser.parse_args()
    try:
        create_example(arguments.output, arguments.rows)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Generation failed: {error}\n")


if __name__ == "__main__":
    main()
